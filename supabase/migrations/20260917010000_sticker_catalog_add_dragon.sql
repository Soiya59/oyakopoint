-- ============================================================
-- 参照:
--   開発チームのやること.md 5-9「メダルの新しい3種（どんぐり・とり・
--   ドラゴン）をカタログに追加するか」— 統括の指示「じゃあ、ドラゴンを
--   いれてみて」により、3種のうちドラゴンのみを今回追加する。どんぐり
--   （acorn）・とり（bird）・くるま（car）は対象外のまま。
--   開発部/成果物/実装メモ.md 177章。
--
-- 前提（本部長が本番DB・実コードで確認済み・2026-09-09）:
--   `assets/stickers/`に`dragon_bronze/silver/gold/crystal`と各`@sm`版
--   （計8枚）が既に揃っている（実装メモ176.3・176.4章）。
--   `sticker_catalog`は12行（形3種=beetle/butterfly/flower×レアリティ4段）。
--
-- 破壊性:
--   (1) `sticker_catalog_shape_check`（CHECK制約）を張り替える。
--       `ARRAY['beetle','butterfly','flower']`→
--       `ARRAY['beetle','butterfly','flower','dragon']`。既存3形の行は
--       一切書き換えない（値の追加のみ、削除・変更なし）ため、
--       20260915010000で確認済みの「同一トランザクション内でも各DML文の
--       実行時点で有効な制約定義を見る」という制約は今回はINSERTが
--       新しい値を使う側なので、実行順序は「DROP CONSTRAINT→ADD
--       CONSTRAINT（新しい許容値）→INSERT」でよい（UPDATEではなくINSERT
--       のため、旧制約に一度も新しい値を通す必要が無い）。
--   (2) `sticker_catalog`へ4行INSERT（dragon×bronze/silver/gold/crystal）。
--       既存12行は一切変更しない。
--
-- 価格・命名の流儀: 既存3形と同じ 銅10／銀30／金50／クリスタル100pt。
--   `display_name`は既存の「レアリティ＋の＋形」の並び（どうの◯◯／
--   ぎんの◯◯／きんの◯◯／クリスタルの◯◯）を踏襲し、◯◯は「ドラゴン」
--   （カタカナ）とした。既存の「カブトムシ」「ちょうちょ」「ちいさなはな」
--   はひらがな寄りだが、「ドラゴン」は外来語のため対応する自然な訓読み・
--   ひらがな表記が無く、173.3章で「クリスタル」を外来語としてカタカナ
--   統一した理由と同じ考え方でカタカナ表記とした。
--
-- 段階購入制（要件定義書07-19-14章、実装メモ173.2章・20260911010000/
--   20260915010000）・月次購入上限撤廃（決定39）は、いずれも`sticker_key`・
--   `display_name`の追加ではなく`shape`カラムをキーにEXISTS判定する既存の
--   `purchase_sticker(UUID)`ロジックがそのまま機能する（`sc.shape =
--   v_catalog.shape`という一般化された条件で、形の一覧をハードコードして
--   いない）。したがって`purchase_sticker`・`computeLockedCatalogIds`
--   （src/hooks/useStickers.ts）ともに変更不要（開発部/成果物/実装メモ.md
--   177.4章で実測により確認する）。追加直後は「ドラゴンの銅だけ買える、
--   他3つは家族解放待ちで買えない」が期待動作になる（銅は無条件、銀・金・
--   クリスタルは家族の誰かが同じ形のひとつ下のレアリティを過去に購入した
--   ことがある場合のみ）。
--
-- 既存の適用済みマイグレーションファイル（20260907020000等）は書き換えない
-- （経緯が読めなくなるため。20260910010000・20260915010000と同じ方針）。
-- ============================================================


-- ------------------------------------------------------------
-- 1. CHECK制約を張り替える（DROP→ADD。新しい値はINSERT側でのみ使うため、
--    20260915010000のような「先に外す必要」は無いが、同じ手順に揃えて
--    読みやすくする）
-- ------------------------------------------------------------
ALTER TABLE sticker_catalog DROP CONSTRAINT IF EXISTS sticker_catalog_shape_check;

ALTER TABLE sticker_catalog ADD CONSTRAINT sticker_catalog_shape_check
  CHECK (shape IN ('beetle', 'butterfly', 'flower', 'dragon'));


-- ------------------------------------------------------------
-- 2. ドラゴン4段階をINSERT
-- ------------------------------------------------------------
INSERT INTO sticker_catalog (shape, rarity, sticker_key, display_name, points_cost) VALUES
  ('dragon', 'bronze',  'dragon_bronze',  'どうのドラゴン',       10),
  ('dragon', 'silver',  'dragon_silver',  'ぎんのドラゴン',       30),
  ('dragon', 'gold',    'dragon_gold',    'きんのドラゴン',       50),
  ('dragon', 'crystal', 'dragon_crystal', 'クリスタルのドラゴン', 100)
ON CONFLICT (sticker_key) DO NOTHING;
