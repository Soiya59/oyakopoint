-- 07-13章DB基盤（前マイグレーション20260825120000）の適用直後に発覚した
-- 権限設定の不備を修正: draw_gacha() / decorate_tree_with_gacha_prize() から
-- anonのEXECUTE権限を明示的に剥奪する
-- ============================================================
-- [経緯] 20260825120000マイグレーション適用後、本番のpg_proc.proaclを確認した
-- ところ、draw_gacha() / decorate_tree_with_gacha_prize() のACLに
-- `anon=X/postgres` が含まれていることが判明した（本来anonには一切許可しない
-- 設計・スキーマ設計.sql 33g章「[方針2] ...anonには一切許可しない」/
-- API仕様.md 12.6節）。
--
-- [原因] 20260823100000マイグレーション（家族の木・週次ダイジェスト機能）の
-- 適用時に開発部が確認した既知の事象と同じ原因: 本Supabaseプロジェクトでは
-- publicスキーマに新規作成した関数に対し、Supabase側の設定（デフォルト権限）に
-- よりanon/authenticatedロールへEXECUTE権限が「PUBLIC経由ではなく直接」
-- 自動付与される。スキーマ設計.sql 33g章のSQL本文は
-- `REVOKE ALL ... FROM PUBLIC` のみを記述しており、anonへの直接付与分は
-- 剥奪されないまま残っていた（32b章のコメントが指摘した論点――「本設計書には
-- REVOKE ... FROM PUBLICの記述が足りない」――と同種の見落としが、今回は
-- 「anonロールへの明示的なREVOKEの欠落」という形で実際に発生していたことに
-- なる）。20260823100000マイグレーションでは
-- `REVOKE EXECUTE ... FROM PUBLIC, anon, authenticated` と、既にanonを含めた
-- 形で適用済みだったため同種の問題は起きていなかった。
--
-- [設計書との関係] 本修正はスキーマ設計.sql 33g章が明記した設計意図
-- 「anonには一切許可しない」をそのまま実現するための技術的補正であり、
-- 権限方針そのもの（authenticatedのみ許可）を変更するものではない。
-- 新規の設計判断は含まないため、開発部の技術的補正として即時対応し、
-- 内容を実装メモ.mdに記録する（本部長への報告事項）。
--
-- [影響範囲] 権限（GRANT/REVOKE）の変更のみ。テーブル・関数の定義・データには
-- 一切触れない。anonは元々`current_family_member_id()`がNULLを返すため
-- これらの関数を呼んでも内部で例外になり実害は無かったが、
-- 「呼び出し自体をロールレベルで拒否する」という設計意図を満たすため修正する。
-- ============================================================

REVOKE EXECUTE ON FUNCTION public.draw_gacha() FROM anon;
REVOKE EXECUTE ON FUNCTION public.decorate_tree_with_gacha_prize(UUID, UUID) FROM anon;
