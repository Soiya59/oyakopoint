/**
 * 全角/半角・大文字/小文字・ひらがな/カタカナを正規化する（決定16）。
 * - NFKC正規化で全角英数記号を半角に寄せる（例: "ＡＢＣ" → "ABC"）。
 * - 小文字化する。
 * - ひらがなをカタカナへ寄せる（NG_WORDS側・入力側の双方をこの関数に通すため、
 *   どちらの表記で書かれていても一致する）。
 */
export function normalizeForNgWordCheck(input: string): string {
  return input
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ぁ-ゖ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) + 0x60));
}

/**
 * 入力にNGワードが含まれるか（部分一致、決定16）。NG_WORDSが空の間は常にfalse。
 */
export function containsNgWord(input: string, words: readonly string[] = NG_WORDS): boolean {
  if (!input || words.length === 0) return false;
  const normalized = normalizeForNgWordCheck(input);
  return words.some((w) => w && normalized.includes(normalizeForNgWordCheck(w)));
}

